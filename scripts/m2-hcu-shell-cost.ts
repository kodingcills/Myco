/**
 * TIF-268 (M2-05) - the cost estimate for the hcu+shell arm's M2-12 runs. Arithmetic only:
 * this calls no model and spends nothing.
 *
 *   pnpm tsx scripts/m2-hcu-shell-cost.ts           print the estimate block
 *   pnpm tsx scripts/m2-hcu-shell-cost.ts --check   fail unless the arm doc quotes it
 *
 * The measured base is C1 arm-003 r6 (`docs/research/experiments/c1-arm-003/r6/
 * ledger-extract.json`): the same task, model, output ceiling and 30-step budget, and the
 * closest thing to this arm that has been run. Per planner call, r6 cost a known number of
 * micros. The hcu+shell arm sends the same screenshot and prompt plus up to SHELL_HISTORY
 * shell results, so its per-call cost is r6's plus the added input tokens. Rates are the
 * repo's frozen Sonnet 5.5 rates ($2 / $10 per MTok, `src/baseline/planner.ts`), which match
 * the published price for `claude-sonnet-5-5`.
 *
 * Assumptions are named constants below so a reviewer can change one and re-run.
 */
import { readFileSync } from "node:fs";
import { STEP_BUDGET } from "../src/baseline/c1-trial.ts";
import { OUTPUT_CEILING, SHELL_HISTORY } from "../src/baseline/hcu-shell/decision.ts";
import { MAX_SHELL_OUTPUT } from "../src/baseline/hcu-shell/shell-tool.ts";

export const EXTRACT = "docs/research/experiments/c1-arm-003/r6/ledger-extract.json";
export const DOC = "docs/research/m2-hcu-shell-arm.md";

/** R2's paired-trial count (`docs/product/m2-plan-draft.md` §2.1). */
export const TRIALS = 30;
/** Frozen rates, micros per token (planner.ts: `input * 2 + output * 10`). */
const INPUT_MICROS = 2;
const OUTPUT_MICROS = 10;
/** C1's per-call input bound (planner.ts MAX_INPUT). */
const C1_MAX_INPUT = 5_000;
/**
 * Conservative characters per token for shell output (CSV and paths tokenize worse than
 * prose's ~4). Used to turn the character cap into a token bound.
 */
const CHARS_PER_TOKEN = 3;
/** Extra prompt tokens for the shell sentence; measured by character count / 3, rounded up. */
const PROMPT_EXTRA_TOKENS = 100;
/**
 * Expected case: about one shell result in context on an average call. A task fixture is
 * 5-200 rows, so a convert-csv result is usually near the 4,096-char cap; one slot is used.
 */
const EXPECTED_SLOTS = 1;

interface R6Row {
  steps: number;
  claims: string[];
  micros: number;
  deviations: string[];
}

export function estimate(extract = JSON.parse(readFileSync(EXTRACT, "utf8")) as { rows: R6Row[] }) {
  const rows = extract.rows;
  if (rows.length === 0) throw new Error("r6 extract has no rows");
  // A trial makes one call per step, plus one more when it ended on a claim or an
  // unreadable reply rather than on the budget.
  const calls = rows.reduce(
    (n, r) =>
      n + r.steps + (r.claims.length > 0 || r.deviations.includes("planner-no-action") ? 1 : 0),
    0,
  );
  const micros = rows.reduce((n, r) => n + r.micros, 0);
  const r6PerCall = micros / calls;
  const r6CallsPerTrial = calls / rows.length;
  const slotTokens = Math.ceil(MAX_SHELL_OUTPUT / CHARS_PER_TOKEN);

  const expectedPerCall =
    r6PerCall + (PROMPT_EXTRA_TOKENS + EXPECTED_SLOTS * slotTokens) * INPUT_MICROS;
  const expectedPerTrial = expectedPerCall * r6CallsPerTrial;

  const ceilingInput = C1_MAX_INPUT + PROMPT_EXTRA_TOKENS + SHELL_HISTORY * slotTokens;
  const ceilingPerCall = ceilingInput * INPUT_MICROS + OUTPUT_CEILING * OUTPUT_MICROS;
  // STEP_BUDGET acting calls plus the final claim.
  const ceilingPerTrial = ceilingPerCall * (STEP_BUDGET + 1);

  const usd = (m: number) => `$${(m / 1_000_000).toFixed(2)}`;
  const usd4 = (m: number) => `$${(m / 1_000_000).toFixed(4)}`;
  return {
    r6: { rows: rows.length, calls, micros, perCallMicros: Math.round(r6PerCall) },
    expected: {
      perTrialMicros: Math.round(expectedPerTrial),
      armMicros: Math.round(expectedPerTrial * TRIALS),
    },
    ceiling: {
      inputTokensPerCall: ceilingInput,
      perTrialMicros: ceilingPerTrial,
      armMicros: ceilingPerTrial * TRIALS,
    },
    block: [
      "<!-- generated by scripts/m2-hcu-shell-cost.ts; do not edit by hand -->",
      "| | Per trial | 30 trials (R2) |",
      "|---|---|---|",
      `| Measured base: C1 r6, ${rows.length} trials, ${calls} planner calls, ${usd4(micros)} | ${usd4(r6PerCall * r6CallsPerTrial)} | ${usd(micros)} |`,
      `| hcu+shell expected (r6 per-call ${usd4(r6PerCall)} + ${PROMPT_EXTRA_TOKENS + EXPECTED_SLOTS * slotTokens} input tokens per call) | ${usd4(expectedPerTrial)} | **${usd(expectedPerTrial * TRIALS)}** |`,
      `| hcu+shell ceiling (${STEP_BUDGET + 1} calls x (${ceilingInput} in + ${OUTPUT_CEILING} out tokens)) | ${usd4(ceilingPerTrial)} | **${usd(ceilingPerTrial * TRIALS)}** |`,
    ].join("\n"),
  };
}

function main() {
  const result = estimate();
  if (process.argv.includes("--check")) {
    const doc = readFileSync(DOC, "utf8");
    if (!doc.includes(result.block)) {
      process.stderr.write(
        `${DOC} does not quote the current estimate; re-run and paste:\n${result.block}\n`,
      );
      process.exit(1);
    }
    process.stdout.write("ok: the arm doc quotes the computed estimate\n");
    return;
  }
  process.stdout.write(`${result.block}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
