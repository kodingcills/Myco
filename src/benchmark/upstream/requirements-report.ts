/**
 * Renders docs/benchmark/upstream/requirements.md from the imported manifests: for every
 * imported task, which benchmark environment runs it and what that harness must provide.
 *
 * Under the lead's 13:55Z ruling (#700 comment 7220110528) there is no Myco placement: every
 * OSWorld task runs in OSWorld's own DesktopEnv (its provider, image and in-VM controller),
 * every WAA task in WAA's own Windows 11 image. Nothing here selects or drops a task.
 *
 * Generated, never hand-edited: `scripts/upstream-import.ts --check` and
 * test/benchmark/upstream-manifest.test.ts fail when the doc and the manifests disagree.
 */
import type { HarnessEnvironment, UpstreamManifest, UpstreamTask } from "./import.ts";

const ENVIRONMENT_MEANING: Record<HarnessEnvironment, string> = {
  "osworld-desktopenv":
    "OSWorld's own `DesktopEnv` at the pinned commit: its provider (Docker/KVM, VMware, VirtualBox, AWS, ...), its Ubuntu image with the apps preinstalled, and its in-VM controller, which runs the setup steps, executes the agent's actions, serves the evaluator's getters and runs the postconfig.",
  "waa-windows-arena":
    "WindowsAgentArena's own Windows 11 image, in-VM server, evaluators and runner. Phase 2: deferred, not dropped.",
};

const CODE_MEANING: Record<string, string> = {
  SEED_ASSETS_LICENSE_UNCLEAR:
    "The task's setup downloads seed files whose license is unclear (README §1, pending ruling `asset-license`). Myco neither fetches nor vendors them; OSWorld's own setup step downloads them inside its environment when a run is allowed.",
  GOLD_ASSETS_LICENSE_UNCLEAR:
    "The evaluator compares against a gold file (`cloud_file`) with an unclear license; same ruling.",
  POSTCONFIG_RUN_BY_UPSTREAM_EVALUATE:
    "The evaluator has postconfig steps (activate a window, Ctrl+S, sleep). `DesktopEnv.evaluate()` runs them itself through its controller before grading; Myco runs none.",
  GETTERS_SERVED_BY_UPSTREAM_CONTROLLER:
    "The evaluator reads guest state (a file, the accessibility tree, a command's output) through its own getters and the in-VM controller. Not an exclusion.",
  NETWORK_PROXY:
    "The task sets `proxy: true`. The pinned Claude runner constructs DesktopEnv with `enable_proxy=False`; recorded for the record.",
  INFEASIBLE_TASK_GRADED_ON_AGENT_FAIL_ACTION:
    "Upstream `infeasible` task: `DesktopEnv.evaluate()` passes it only when the agent's last action is FAIL. An agent that says DONE here is a false done by construction.",
};

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderRequirementsReport(
  sets: readonly { manifest: UpstreamManifest; tasks: readonly UpstreamTask[] }[],
): string {
  const lines: string[] = [];
  lines.push("# Public benchmark subsets: environment and harness requirements per task");
  lines.push("");
  lines.push(
    "> Generated by `scripts/upstream-import.ts` from the manifests under `benchmark/upstream/`. Do not edit by hand. Not a result: no task here has been run. Every task runs in its benchmark's own environment (lead ruling 2026-11-27 ~13:55Z); nothing in this report selects or drops a task.",
  );
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push("| Task set | Upstream @ commit | Environment | Tasks | Per domain | Infeasible | Excluded |");
  lines.push("|---|---|---|---|---|---|---|");
  for (const { manifest } of sets) {
    const perDomain = Object.entries(manifest.counts.perDomain)
      .map(([k, v]) => `${k}: ${v}`)
      .join("; ");
    lines.push(
      `| ${manifest.taskSetVersion} | ${manifest.upstream.name} @ \`${manifest.upstream.commit.slice(0, 12)}\` | ${manifest.environment} | ${manifest.counts.total} | ${perDomain} | ${manifest.counts.infeasible} | ${manifest.counts.excluded} |`,
    );
  }
  lines.push("");
  lines.push("## Exclusions");
  lines.push("");
  for (const { manifest } of sets) {
    const ex = Object.entries(manifest.exclusions);
    lines.push(
      ex.length === 0
        ? `- ${manifest.taskSetVersion}: none. Every listed task in the selected domains is in the set.`
        : `- ${manifest.taskSetVersion}: ${ex.map(([id, why]) => `\`${id}\` (${why})`).join(", ")}`,
    );
  }
  lines.push("");
  lines.push("## Environments");
  lines.push("");
  for (const [k, v] of Object.entries(ENVIRONMENT_MEANING)) lines.push(`- **\`${k}\`**: ${v}`);
  lines.push("");
  lines.push("## Requirement codes");
  lines.push("");
  for (const [k, v] of Object.entries(CODE_MEANING)) lines.push(`- \`${k}\`: ${v}`);
  for (const { manifest, tasks } of sets) {
    lines.push("");
    lines.push(`## ${manifest.taskSetVersion}`);
    lines.push("");
    lines.push(
      "| Task id (upstream, verbatim) | Domain | Evaluator | Getters | Setup | Postconfig | Needs |",
    );
    lines.push("|---|---|---|---|---|---|---|");
    for (const t of tasks) {
      const r = t.requirements;
      lines.push(
        `| \`${t.taskId}\` | ${t.domain} | ${cell(t.evaluator.funcs.join(` ${t.evaluator.conj} `))} | ${cell(r.getters.join(", "))} | ${cell(r.setup.join(", "))} | ${cell(r.postconfig.join(", "))} | ${cell(r.needs.join(", "))} |`,
      );
    }
  }
  lines.push("");
  return lines.join("\n");
}
