/**
 * Renders docs/benchmark/upstream/placement.md from the imported manifests (#682 item 4):
 * for every imported task, where it can run (the Linux namespace desktops or the Windows VM)
 * and why. Generated, never hand-edited: `scripts/upstream-import.ts --check` and
 * test/benchmark/upstream-manifest.test.ts fail when the doc and the manifests disagree.
 */
import type { PlacementTarget, UpstreamManifest, UpstreamTask } from "./import.ts";

const TARGET_MEANING: Record<PlacementTarget, string> = {
  "linux-namespace-desktop":
    "Runs on the Linux namespace desktops: LibreOffice only, and the evaluator grades captured files (or a constant rule), so the host can grade from the bytes the desktop leaves behind.",
  "linux-needs-other-app":
    "OSWorld (Ubuntu) task, but it needs an app the namespace desktop does not ship (it registers LibreOffice only). Runs on Linux once that app is added to the desktop image; never needs Windows.",
  "linux-needs-guest-probe":
    "OSWorld (Ubuntu) task whose evaluator reads live guest state (for example the accessibility tree or a command's output), not a saved file. Needs a guest probe on the desktop before it can be graded.",
  "windows-vm":
    "WindowsAgentArena task: built for WAA's Windows 11 image (Windows paths, Windows apps, WAA's in-guest server). Needs the Windows VM.",
};

const CODE_MEANING: Record<string, string> = {
  LIBREOFFICE_ONLY_FILE_GRADED: "Only LibreOffice apps, and every evaluator getter is file-based.",
  INFEASIBLE_TASK_GRADED_ON_AGENT_FAIL_ACTION:
    "Upstream `infeasible` task: the evaluator passes only if the agent's last action is FAIL. An agent that says done here is a false done by construction.",
  WAA_WINDOWS_IMAGE: "Part of WindowsAgentArena, whose tasks assume WAA's Windows 11 image.",
  WINDOWS_PATHS: "The task's config or evaluator names Windows paths (C:\\...).",
  WINDOWS_ONLY_APP: "Notepad or File Explorer: Windows-only apps.",
  "APP_NOT_ON_DESKTOP:<app>":
    "Needs this app on the desktop; the namespace desktop has none but LibreOffice.",
  "GUEST_PROBE_GETTER:<getter>":
    "This upstream getter reads live guest state, not a captured file.",
  SEED_ASSETS_LICENSE_UNCLEAR:
    "Needs: the task downloads seed files whose license is unclear; they are not fetched until a lead ruling (README §1).",
  POSTCONFIG_EXECUTOR:
    "Needs: the upstream evaluator runs postconfig steps (activate a window, press Ctrl+S, sleep) before grading; the harness must execute them in the desktop.",
  NETWORK_PROXY:
    "Needs: the task sets `proxy: true` (network); namespace desktops have networking off by default.",
};

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderPlacementReport(
  sets: readonly { manifest: UpstreamManifest; tasks: readonly UpstreamTask[] }[],
): string {
  const lines: string[] = [];
  lines.push("# Public benchmark subsets: where each task runs");
  lines.push("");
  lines.push(
    "> Generated by `scripts/upstream-import.ts` from the manifests under `benchmark/upstream/`. Do not edit by hand. This is a placement report, not a result: no task here has been run.",
  );
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push("| Task set | Upstream @ commit | Tasks | Placement counts |");
  lines.push("|---|---|---|---|");
  for (const { manifest } of sets) {
    const counts = Object.entries(manifest.counts.perPlacement)
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([k, v]) => `${k}: ${v}`)
      .join("; ");
    lines.push(
      `| ${manifest.taskSetVersion} | ${manifest.upstream.name} @ \`${manifest.upstream.commit.slice(0, 12)}\` | ${manifest.counts.total} | ${counts} |`,
    );
  }
  lines.push("");
  lines.push("## Placement targets");
  lines.push("");
  for (const [k, v] of Object.entries(TARGET_MEANING)) lines.push(`- **\`${k}\`**: ${v}`);
  lines.push("");
  lines.push("## Reason and requirement codes");
  lines.push("");
  for (const [k, v] of Object.entries(CODE_MEANING)) lines.push(`- \`${k}\`: ${v}`);
  for (const { manifest, tasks } of sets) {
    lines.push("");
    lines.push(`## ${manifest.taskSetVersion}`);
    lines.push("");
    lines.push(
      "| Task id (upstream, verbatim) | Domain | Apps | Evaluator | Placement | Why | Needs |",
    );
    lines.push("|---|---|---|---|---|---|---|");
    for (const t of tasks) {
      lines.push(
        `| \`${t.taskId}\` | ${t.domain} | ${cell(t.relatedApps.join(", "))} | ${cell(t.evaluator.funcs.join(` ${t.evaluator.conj} `))} | ${t.placement.target} | ${cell(t.placement.reasons.join(", "))} | ${cell(t.placement.needs.join(", "))} |`,
      );
    }
  }
  lines.push("");
  return lines.join("\n");
}
