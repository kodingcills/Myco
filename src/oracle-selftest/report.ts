/**
 * The committed R5 mutation report (M2-09): oracle x corruption class x verdict, plus a
 * generated README. Deterministic (no timestamps, no paths), so `--check` can rebuild it
 * byte for byte (M2 plan: "re-run the mutation suite and diff against the committed report").
 */
import { type OracleReport, runSelfTest, type SelfTestRow } from "./run.ts";
import {
  calcCases,
  calcGateOracle,
  calcGateXlsxOracle,
  calcRecordEditOracle,
  calcXlsxCases,
  writerCases,
  writerOracle,
} from "./subjects.ts";
import { CORRUPTION_CLASSES, EXPECTED_STATUS } from "./types.ts";

export const REPORT_SCHEMA = "myco.oracle-selftest/1";

export interface SelfTestBundle {
  readonly schema: typeof REPORT_SCHEMA;
  readonly reports: readonly OracleReport[];
  readonly rows: readonly SelfTestRow[];
}

export function buildSelfTest(): SelfTestBundle {
  const cases = calcCases();
  const results = [
    runSelfTest(calcRecordEditOracle, cases),
    runSelfTest(calcGateOracle, cases),
    runSelfTest(calcGateXlsxOracle, calcXlsxCases()),
    runSelfTest(writerOracle, writerCases()),
  ];
  return {
    schema: REPORT_SCHEMA,
    reports: results.map((r) => r.report),
    rows: results.flatMap((r) => r.rows),
  };
}

export function renderJson(bundle: SelfTestBundle): string {
  return `${JSON.stringify(bundle, null, 2)}\n`;
}

export function renderReadme(bundle: SelfTestBundle): string {
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);
  push("# Oracle mutation self-test (M2-09 / R5), part 1", "");
  push("Generated by `npx tsx scripts/oracle-selftest.ts --write`. Do not edit by hand:");
  push(
    "`--check` rebuilds this file and `report.json` byte for byte and fails on any difference.",
    "",
  );
  push("Each oracle is run through its real read path on seeded corruptions of a correct saved");
  push("document. **Bar:** every correct document verifies, and for every class the oracle");
  push("*claims*, at least one corruption is run and none of them verifies. A corruption whose");
  push("bytes equal the correct document is a harness fault and fails the bar. Unclaimed classes");
  push("are run and reported but do not count toward the bar: a verified unclaimed row is a");
  push(
    "visible gap, not a pass. **A PASS means the claimed classes are caught, nothing more.**",
    "",
  );
  for (const r of bundle.reports) {
    push(`## \`${r.oracle}\` (version ${r.version}): ${r.pass ? "PASS" : "FAIL"}`, "");
    push(`Cases: ${r.cases}. Correct documents verified: ${r.controlsVerified}/${r.cases}.`);
    if (r.reasons.length > 0) push(`Reasons: ${r.reasons.join("; ")}.`);
    push("");
    push(
      "| Class | Claimed | Expected verdict | Caught (not verified) | With the expected verdict |",
    );
    push("|---|---|---|---|---|");
    for (const cls of CORRUPTION_CLASSES) {
      const s = r.perClass[cls];
      if (s.runs === 0) {
        push(
          `| \`${cls}\` | no | ${EXPECTED_STATUS[cls]} | not applicable to this format (not run) | n/a |`,
        );
        continue;
      }
      push(
        `| \`${cls}\` | ${s.claimed ? "yes" : "no"} | ${EXPECTED_STATUS[cls]} | ${s.caught}/${s.runs} | ${s.expectedStatus}/${s.runs} |`,
      );
    }
    push("");
  }
  push("## What this report shows (each statement is asserted by `test/oracle-selftest/`)", "");
  push("- **Collateral damage** (target right, other content changed) verifies on M1's");
  push("  `calc-record-edit/csv` verifier and on `writer-doc-edit`: both check the target only.");
  push("  The gate's `calc-record-edit` family (version 2, TIF-270 / #485) reads the same CSV");
  push("  bytes, checks the whole document, and refutes every collateral corruption.");
  push("- **A truncated CSV** verifies on M1's CSV verifier exactly when the target cell");
  push("  survives the cut: CSV has no integrity marker, and that verifier reads one cell. The");
  push("  gate's whole-document check refutes every truncated CSV (the missing rows differ).");
  push("- **`writer-doc-edit` PASS is not whole-document correctness:** it does not claim");
  push("  collateral, and a collateral corruption verifies on it.");
  push("- Classes marked *not applicable* were not run for that oracle: a CSV has no container,");
  push("  so `corrupt-byte`, `partial-save` and `missing-main-part` have no CSV form.", "");
  push("Agent-written oracles and the oracle-authoring cost (the rest of R5) need paid model");
  push("runs; they plug into the same runner (`OracleUnderTest`) and the same bar.", "");
  return lines.join("\n");
}
