/**
 * The committed R5 mutation report (M2-09): oracle x corruption class x verdict, plus a
 * generated README. Deterministic (no timestamps, no paths), so `--check` can rebuild it
 * byte for byte (M2 plan: "re-run the mutation suite and diff against the committed report").
 */
import { type OracleReport, runSelfTest, type SelfTestRow } from "./run.ts";
import { calcCases, calcRecordEditOracle, writerCases, writerOracle } from "./subjects.ts";
import { CORRUPTION_CLASSES, EXPECTED_STATUS } from "./types.ts";

export const REPORT_SCHEMA = "myco.oracle-selftest/1";

export interface SelfTestBundle {
  readonly schema: typeof REPORT_SCHEMA;
  readonly reports: readonly OracleReport[];
  readonly rows: readonly SelfTestRow[];
}

export function buildSelfTest(): SelfTestBundle {
  const calc = runSelfTest(calcRecordEditOracle, calcCases());
  const writer = runSelfTest(writerOracle, writerCases());
  return {
    schema: REPORT_SCHEMA,
    reports: [calc.report, writer.report],
    rows: [...calc.rows, ...writer.rows],
  };
}

export function renderJson(bundle: SelfTestBundle): string {
  return `${JSON.stringify(bundle, null, 2)}\n`;
}

export function renderReadme(bundle: SelfTestBundle): string {
  const lines: string[] = [];
  lines.push("# Oracle mutation self-test (M2-09 / R5), part 1");
  lines.push("");
  lines.push("Generated by `npx tsx scripts/oracle-selftest.ts --write`. Do not edit by hand:");
  lines.push(
    "`--check` rebuilds this file and `report.json` byte for byte and fails on any difference.",
  );
  lines.push("");
  lines.push(
    "Each oracle is run through its real read path on seeded corruptions of a correct saved",
  );
  lines.push("document. **Bar:** every correct document verifies, and for every class the oracle");
  lines.push(
    "*claims*, at least one corruption is run and none of them verifies. Unclaimed classes",
  );
  lines.push("are run and reported but do not count toward the bar; a verified unclaimed row is a");
  lines.push("visible gap, not a pass.");
  lines.push("");
  for (const r of bundle.reports) {
    lines.push(`## \`${r.oracle}\` (version ${r.version}): ${r.pass ? "PASS" : "FAIL"}`);
    lines.push("");
    lines.push(`Cases: ${r.cases}. Correct documents verified: ${r.controlsVerified}/${r.cases}.`);
    if (r.reasons.length > 0) lines.push(`Reasons: ${r.reasons.join("; ")}.`);
    lines.push("");
    lines.push(
      "| Class | Claimed | Expected verdict | Caught (not verified) | With the expected verdict |",
    );
    lines.push("|---|---|---|---|---|");
    for (const cls of CORRUPTION_CLASSES) {
      const s = r.perClass[cls];
      if (s.runs === 0) continue;
      lines.push(
        `| \`${cls}\` | ${s.claimed ? "yes" : "no"} | ${EXPECTED_STATUS[cls]} | ${s.caught}/${s.runs} | ${s.expectedStatus}/${s.runs} |`,
      );
    }
    lines.push("");
  }
  lines.push("## Gaps this report makes visible");
  lines.push("");
  lines.push(
    "- **Collateral damage** (target right, other content changed) verifies on both oracles:",
  );
  lines.push(
    "  both check the target only. For Calc, the whole-document check is TIF-270 (#485); it",
  );
  lines.push("  joins this report as a subject when it lands. Writer has no such check yet.");
  lines.push(
    "- **A truncated CSV** verifies on M1's CSV path whenever the target row survives the cut:",
  );
  lines.push(
    "  CSV has no integrity marker, and the verifier reads the target cell only. The live Calc",
  );
  lines.push(
    "  path reads `.xlsx` (a zip container), which a truncation breaks; TIF-267's independent",
  );
  lines.push("  grader also refuses any changed cell.");
  lines.push("");
  lines.push(
    "Agent-written oracles and the oracle-authoring cost (the rest of R5) need paid model",
  );
  lines.push("runs; they plug into the same runner (`OracleUnderTest`) and the same bar.");
  lines.push("");
  return `${lines.join("\n")}`;
}
