/** The glyph set, exactly. */
export const GLYPHS: ReadonlySet<string> = new Set(Object.keys(RAW));

const BITS: ReadonlyMap<string, readonly boolean[]> = new Map(
  Object.entries(RAW).map(([ch, rows]) => [
    ch,
    rows
      .join("")
      .split("")
      .map((c) => c === "#"),
  ]),
);

/** The glyph bitmaps of `text` (row-major, GLYPH_W x GLYPH_H each), or null if any is missing. */
export function glyphsFor(text: string): (readonly boolean[])[] | null {
  const out: (readonly boolean[])[] = [];
  for (const ch of text) {
    const bits = BITS.get(ch);
    if (bits === undefined) return null;
    out.push(bits);
  }
  return out;
}
